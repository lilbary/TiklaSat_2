-- =====================================================================
-- İLETİŞİM BİLGİSİ İFŞA KAYDI (BR-N-004, BR-K-004)
-- ---------------------------------------------------------------------
-- Kullanıcı, kendi telefon numarasının KİME, NE ZAMAN, HANGİ İŞLEM
-- nedeniyle açıldığını sorgulayabilmelidir. Kişisel veri paylaşan bir
-- platform için yasal gerekliliktir ve teknik olarak tek satırlık maliyeti
-- vardır.
-- =====================================================================

CREATE TABLE contact_disclosures (
    id                UUID          PRIMARY KEY DEFAULT gen_random_uuid(),
    auction_id        UUID          NOT NULL,
    viewer_user_id    UUID          NOT NULL,   -- bilgiyi GÖREN
    subject_user_id   UUID          NOT NULL,   -- bilgisi AÇILAN
    disclosed_fields  VARCHAR(100)  NOT NULL,   -- 'PHONE,EMAIL'
    viewer_ip         INET,
    disclosed_at      TIMESTAMPTZ   NOT NULL DEFAULT now(),

    CONSTRAINT fk_disclosures_auction FOREIGN KEY (auction_id)
        REFERENCES auctions (id) ON DELETE RESTRICT,
    CONSTRAINT fk_disclosures_viewer FOREIGN KEY (viewer_user_id)
        REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_disclosures_subject FOREIGN KEY (subject_user_id)
        REFERENCES users (id) ON DELETE RESTRICT,

    CONSTRAINT uq_disclosures UNIQUE (auction_id, viewer_user_id, subject_user_id),
    CONSTRAINT ck_disclosures_not_self CHECK (viewer_user_id <> subject_user_id)
);

-- "Benim bilgim kime açıldı?" sorgusu (KVKK bilgi talebi)
CREATE INDEX ix_disclosures_subject ON contact_disclosures (subject_user_id, disclosed_at DESC);

