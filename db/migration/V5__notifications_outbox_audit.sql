CREATE TABLE user_ratings (
    id          UUID          PRIMARY KEY DEFAULT gen_random_uuid(),
    auction_id  UUID          NOT NULL,
    rater_id    UUID          NOT NULL,
    ratee_id    UUID          NOT NULL,
    score       SMALLINT      NOT NULL,
    comment     VARCHAR(500),
    created_at  TIMESTAMPTZ   NOT NULL DEFAULT now(),

    CONSTRAINT fk_ratings_auction FOREIGN KEY (auction_id)
        REFERENCES auctions (id) ON DELETE RESTRICT,
    CONSTRAINT fk_ratings_rater FOREIGN KEY (rater_id)
        REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_ratings_ratee FOREIGN KEY (ratee_id)
        REFERENCES users (id) ON DELETE RESTRICT,

    -- Bir kişi bir artırmada bir kez puan verir
    CONSTRAINT uq_ratings_auction_rater UNIQUE (auction_id, rater_id),

    CONSTRAINT ck_ratings_score CHECK (score BETWEEN 1 AND 5),
    CONSTRAINT ck_ratings_not_self CHECK (rater_id <> ratee_id)
);

CREATE INDEX ix_ratings_ratee ON user_ratings (ratee_id, created_at DESC);

